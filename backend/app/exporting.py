"""Markdown rendering/export. Exports contain AI notes + links only - never stored source transcripts."""
from .models import Claim, Digest, Note, Synthesis
from .transcript import fmt_ts

DISCLAIMER = "> AI-generated notes. Accuracy is not guaranteed; verify against the original video and sources."


def video_url(vid: str, t: float | None = None) -> str:
    return f"https://www.youtube.com/watch?v={vid}" + (f"&t={int(t)}s" if t is not None else "")


def note_markdown(n: Note, claims: list[Claim] | None = None) -> str:
    v = n.video
    lines = [f"# {n.title}", "", f"- Video: [{v.title}]({video_url(v.youtube_video_id)})",
             f"- Generated by: {n.provider} / {n.model} (prompt {n.prompt_version}), v{n.version}",
             f"- Tags: {', '.join(n.tags) or '-'}", "", DISCLAIMER, ""]
    if n.edited_md:
        lines += ["## Notes (edited by you)", "", n.edited_md, ""]
    else:
        lines += ["## Key points", ""]
        for p in n.points:
            mark = "source" if p["kind"] == "source" else "AI-added"
            ts = f" [{fmt_ts(p['t'])}]({video_url(v.youtube_video_id, p['t'])})" if p.get("t") is not None else ""
            lines.append(f"- {p['text']} _({mark})_{ts}")
        if n.action_items:
            lines += ["", "## Action items", ""] + [f"- [ ] {a}" for a in n.action_items]
        if n.glossary:
            lines += ["", "## Glossary", ""] + [f"- **{g['term']}**: {g['explanation']}" for g in n.glossary]
    if n.user_notes:
        lines += ["", "## My notes", "", n.user_notes]
    if claims:
        lines += ["", "## Cross-check", ""]
        for c in claims:
            lines.append(f"- **{c.verdict}** - {c.text}")
            for e in c.evidence:
                lines.append(f"  - {e.stance}: [{e.title or e.url}]({e.url}) (retrieved {e.retrieved_at:%Y-%m-%d})")
    return "\n".join(lines) + "\n"


def library_markdown(notes: list[Note]) -> str:
    out = ["# My Knowledge Library", "", DISCLAIMER, ""]
    for n in notes:
        out.append(note_markdown(n).replace("# ", "## ", 1))
    return "\n".join(out)


def synthesis_markdown(s: Synthesis) -> str:
    return s.markdown


def digest_markdown(d: Digest) -> str:
    return d.markdown
